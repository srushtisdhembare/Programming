#include<stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name : Display
//  Input         : char
//  Output        : void
//  Description   : Use to display capital letter if input is small and vice versa
//  Date          : 29/09/2026
//  Author        : Srushti Sachin Dhembare
//
/////////////////////////////////////////////////////////////////////////////////////////

void Display(char ch)
{
   if((ch >= 'a') && (ch <= 'z'))
   {
        printf("%c\n",ch-32);
   }
   else if((ch >= 'A') && (ch <= 'Z'))
   {
        printf("%c\n",ch+32);
   }
   else 
   {
        printf("%c\n",ch);
   }
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to accept character from user. If it is small then display its corresponding
// capital and vice versa . In other cases display as it is.
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cValue = '\0';

    printf("Enter the character :\n");
    scanf("%c",&cValue);

    Display(cValue);

    return 0;
}

