//  Function name : StrCpySmall
//  Input         : 2 char array
//  Output        : void
//  Description   : Use to accept string & copy small letters of that string into 
//                  another string
//  Date          : 7/10/2026
//  Author        : Srushti Sachin Dhembare
//
/////////////////////////////////////////////////////////////////////////////////////////

void StrCpySmall(char *src, char *dest)
{
    // Filter
    while((*src != '\0'))
    {
        if((*src >= 'a') && (*src <= 'z'))
        {
            *dest = *src;
            dest++;
        }
        src++;
    }

    *dest = '\0';
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accept string and copy small letters of that string into 
// another string . 
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[30] = "Marvellous Multi OS";
    char brr[30];
  
    StrCpySmall(arr,brr);
   
    printf("%s\n",brr);

    return 0;
}

