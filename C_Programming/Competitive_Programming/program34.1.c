void StrCpyX(char *src, char *dest)
{
    // Filter
    while(*src != '\0')
    {
        *dest = *src;
        src++;
        dest++;
    }

    *dest = '\0';
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accept string and copy contents of that string into 
// another string (Using strcpy())
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[30] = "Marvellous Multi OS";
    char brr[30];
  
    StrCpyX(arr,brr);
   
    printf("%s\n",brr);

    return 0;
}

