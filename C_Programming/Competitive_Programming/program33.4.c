int LastChar(char *str, char ch)
{
    int iCount = strlen(str);
    int iIndex = -1;
    int iCnt = 0;

    for(iCnt = iCount - 1; iCnt >= 0; iCnt--)
    {
        if(str[iCnt] == ch)
        {
            return iCnt;
        }  
    } 
     //return iIndex;
}

