int StrRevX(char *str)
{
    int iSize = strlen(str);
    char Arr[iSize];
    int iCount = 0;

    for(int iCnt = iSize - 1, iCount = 0; iCnt >= 0; iCnt--, iCount++)
    {
       Arr[iCount] = str[iCnt];   
    } 
    
    Arr[iSize] = '\0';
    printf("Modified String is %s\n",Arr);
}

