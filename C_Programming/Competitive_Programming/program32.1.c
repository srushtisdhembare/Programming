void LowerCase(char *str)
{
    for(int iCnt = 0; iCnt < strlen(str); iCnt++)
    {
        if(str[iCnt] >= 'A' && str[iCnt] <= 'Z')
        {
            str[iCnt] = str[iCnt] + 32;
        }
        printf("%c",str[iCnt]);
    } 
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accept string and convert it to lower case
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[20];
    
    printf("Enter string :\n");
    scanf("%[^'\n']s",arr);

    LowerCase(arr);

    return 0;
}

