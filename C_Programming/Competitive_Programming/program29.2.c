#include<stdio.h>

#define TRUE 1
#define FALSE 0

typedef int BOOL;
/////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name : ChkCapital
//  Input         : char
//  Output        : BOOL
//  Description   : Use to check whether capital or not
//  Date          : 29/09/2026
//  Author        : Srushti Sachin Dhembare
//
/////////////////////////////////////////////////////////////////////////////////////////

BOOL ChkCapital(char ch)
{
   if((ch >= 'A' && ch <= 'Z')) 
   {
        return TRUE;
   } 
   else
   {
        return FALSE;
   }
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to Accept character from user & check whether it is capital or not
// i.e (A-Z)
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cValue = '\0';
    BOOL bRet = FALSE;

    printf("Enter the character :\n");
    scanf("%c",&cValue);

    bRet = ChkCapital(cValue);

    if(bRet)
    {
        printf("It is a Capital letter\n");
    }
    else 
    {
        printf("It is NOT a Capital letter\n");
    }

    return 0;
}

