int FirstChar(char *str, char ch)
{
    int iCount = 0, iIndex = -1;

    for(int iCnt = 0; iCnt < strlen(str); iCnt++)
    {
        if(str[iCnt] == ch)
        {
            iIndex = iCnt;
        }  
    } 
     return iIndex;
}

