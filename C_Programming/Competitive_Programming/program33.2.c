int ChkChar(char *str, char ch)
{
    int iCount = 0, iFreq = 0;

    for(int iCnt = 0; iCnt < strlen(str); iCnt++)
    {
        if(str[iCnt] == ch)
        {
            iFreq++;
        }  
    } 
     return iFreq;
}

