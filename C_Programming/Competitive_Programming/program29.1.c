#include<stdio.h>

#define TRUE 1
#define FALSE 0

typedef int BOOL;
/////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name : ChkAlpha
//  Input         : char
//  Output        : BOOL
//  Description   : Use to check whether alphabet or not
//  Date          : 29/09/2026
//  Author        : Srushti Sachin Dhembare
//
/////////////////////////////////////////////////////////////////////////////////////////

BOOL ChkAlpha(char ch)
{
   if((ch >= 'A' && ch <= 'Z') || (ch >= 'a' && ch <= 'z')) 
   {
        return TRUE;
   } 
   else
   {
        return FALSE;
   }
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to Accept character from user & check whether it is an alphabet or not
// i.e (A-Z/ a-z)
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cValue = '\0';
    BOOL bRet = FALSE;

    printf("Enter the character :\n");
    scanf("%c",&cValue);

    bRet = ChkAlpha(cValue);

    if(bRet)
    {
        printf("It is a Character\n");
    }
    else 
    {
        printf("It is NOT Character\n");
    }

    return 0;
}

