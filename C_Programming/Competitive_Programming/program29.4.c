#include<stdio.h>

#define TRUE 1
#define FALSE 0

typedef int BOOL;
/////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name : ChkSmall
//  Input         : char
//  Output        : BOOL
//  Description   : Use to check whether small letter or not
//  Date          : 29/09/2026
//  Author        : Srushti Sachin Dhembare
//
/////////////////////////////////////////////////////////////////////////////////////////

BOOL ChkSmall(char ch)
{
   if((ch >= 'a' && ch <= 'z')) 
   {
        return TRUE;
   } 
   else
   {
        return FALSE;
   }
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to Accept character from user & check whether it is small letter or not
// i.e (a-z)
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cValue = '\0';
    BOOL bRet = FALSE;

    printf("Enter the character :\n");
    scanf("%c",&cValue);

    bRet = ChkSmall(cValue);

    if(bRet)
    {
        printf("It is a small letter\n");
    }
    else 
    {
        printf("It is NOT a small letter\n");
    }

    return 0;
}

