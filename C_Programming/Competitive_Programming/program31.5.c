void Reverse(char *str)
{
    int iCnt1 = 0, iCnt2 = 0;
    char Arr[strlen(str)];

    for(iCnt1 = strlen(str)-1,iCnt2 = 0; iCnt1 >= 0; iCnt1--,iCnt2++)
    {     
        Arr[iCnt2] = str[iCnt1];
    }
    Arr[iCnt2] = '\0';

    printf("%s\n",Arr); 
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accept string and display it in reverse order
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[20];
    
    printf("Enter string :\n");
    scanf("%[^'\n']s",arr);

    Reverse(arr);

    return 0;
}

