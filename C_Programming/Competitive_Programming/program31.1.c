int CountCapital(char *str)
{
   int iCnt = 0;

   while(*str != '\0')
   {
        if(*str >= 'A' && *str <= 'Z')
        {
            iCnt++;
        }
        str++;
   }
   return iCnt;
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accpet string and count no. of capital letters
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[20];
    int iRet = 0;
    
    printf("Enter string :\n");
    scanf("%[^'\n']s",arr);

    iRet = CountCapital(arr);

    printf("No. of capital letters are : %d\n",iRet);

    return 0;
}

