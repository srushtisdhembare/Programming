BOOL ChkVowel(char *str)
{
  
   while(*str != '\0')
   {
        if(*str == 'a' || *str == 'e' || *str == 'o' || *str == 'i' || *str == 'u' ||
           *str == 'A' || *str == 'E' || *str == 'O' || *str == 'I' || *str == 'U')
        {
            return TRUE;
        }
        str++;
   }
   
   return FALSE;
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accept string and check if it contains vowel or not.
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[20];
    BOOL bRet = FALSE;
    
    printf("Enter string :\n");
    scanf("%[^'\n']s",arr);

    bRet = ChkVowel(arr);

    if(bRet)
    {
        printf("TRUE\n");
    }
    else 
    {
        printf("FALSE\n");
    }

    return 0;
}

