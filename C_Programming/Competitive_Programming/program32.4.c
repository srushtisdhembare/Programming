void DisplayDigits(char *str)
{
    for(int iCnt = 0; iCnt < strlen(str); iCnt++)
    {
        if(str[iCnt] >= '0' && str[iCnt] <= '9')
        {
            printf("%c",str[iCnt]);
        }  
    } 
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accept string and display only digits from that string
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[20];
    
    printf("Enter string :\n");
    scanf("%[^'\n']s",arr);

    DisplayDigits(arr);

    return 0;
}

