#include<stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name : Display
//  Input         : char
//  Output        : BOOL
//  Description   : Use to display ascii value of char in decimal,octal,hex
//  Date          : 29/09/2026
//  Author        : Srushti Sachin Dhembare
//
/////////////////////////////////////////////////////////////////////////////////////////

void Display(char ch)
{
   printf("Decimal  : %d\n",ch);
   printf("Octal : 0%o\n",(unsigned char)ch);
   printf("Hexadecimal : 0x%x\n",ch);
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to display ascii value of char in decimal , octal , hexadecimal.
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cValue = '\0';
    
    printf("Enter the character :\n");
    scanf("%c",&cValue);

    Display(cValue);

    return 0;
}

