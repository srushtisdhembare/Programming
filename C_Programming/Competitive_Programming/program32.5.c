int CountSpaces(char *str)
{
    int iCount = 0;

    for(int iCnt = 0; iCnt < strlen(str); iCnt++)
    {
        if(str[iCnt] == ' ')
        {
            iCount++;
        }  
    } 
     return iCount;
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accept string and Count the number of Spaces
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[20];
    int iRet = 0;
    
    printf("Enter string :\n");
    scanf("%[^'\n']s",arr);

    iRet = CountSpaces(arr);
    printf("Number of white spaces are : %d\n",iRet);

    return 0;
}

