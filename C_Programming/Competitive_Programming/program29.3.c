#include<stdio.h>

#define TRUE 1
#define FALSE 0

typedef int BOOL;
/////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name : ChkDigit
//  Input         : char
//  Output        : BOOL
//  Description   : Use to check whether digit or not
//  Date          : 29/09/2026
//  Author        : Srushti Sachin Dhembare
//
/////////////////////////////////////////////////////////////////////////////////////////

BOOL ChkDigit(char ch)
{
   if((ch >= '0' && ch <= '9')) 
   {
        return TRUE;
   } 
   else
   {
        return FALSE;
   }
     
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to Accept character from user & check whether it is digit or not
// i.e (0-9)
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cValue = '\0';
    BOOL bRet = FALSE;

    printf("Enter the character :\n");
    scanf("%c",&cValue);

    bRet = ChkDigit(cValue);

    if(bRet)
    {
        printf("It is a Digit\n");
    }
    else 
    {
        printf("It is NOT a Digit\n");
    }

    return 0;
}

