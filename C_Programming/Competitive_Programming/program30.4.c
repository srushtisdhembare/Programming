#include<stdio.h>

#define TRUE 1
#define FALSE 0

typedef int BOOL;
/////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name : Display
//  Input         : char
//  Output        : BOOL
//  Description   : Use to check if i/p char is a special symbol
//  Date          : 29/09/2026
