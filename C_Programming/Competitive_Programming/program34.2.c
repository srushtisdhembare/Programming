void StrNCpyX(char *src, char *dest, int iCnt)
{
    // Filter
    while((*src != '\0') && (iCnt != 0))
    {
        *dest = *src;
        src++;
        dest++;
        iCnt--;
    }

    *dest = '\0';
}

/////////////////////////////////////////////////////////////////////////////////////////
//
// Application to to accept string and copy contents of that string into 
// another string . Implement StrNCpyX() function
//
/////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[30] = "Marvellous Multi OS";
    char brr[30];
  
    StrNCpyX(arr,brr,10);
   
    printf("%s\n",brr);

    return 0;
}

